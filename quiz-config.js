/* คะแนนแบบ Kahoot: ตอบถูกได้ 500 + โบนัสความเร็วสูงสุด 500 */
window.quizScore = function (answeredAt, openedAt, durationSec) {
  var t = (answeredAt - openedAt) / (durationSec * 1000);
  t = Math.min(Math.max(t, 0), 1);
  return Math.round(500 + 500 * (1 - t));
};
