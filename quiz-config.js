/* คะแนนแบบ Kahoot: ตอบถูกได้ 500 + โบนัสความเร็วสูงสุด 500 */
window.quizScore = function (answeredAt, openedAt, durationSec) {
  var t = (answeredAt - openedAt) / (durationSec * 1000);
  t = Math.min(Math.max(t, 0), 1);
  return Math.round(500 + 500 * (1 - t));
};

/* รายการคำถามของสาขา */
window.quizQuestions = function (branch) {
  if (branch.questions) return branch.questions;
  return branch.question ? [{ question: branch.question, options: branch.options }] : [];
};

/* ลำดับสาขา */
window.quizOrder = function () {
  var cfg = window.QUIZ_CONFIG;
  return (cfg.order || Object.keys(cfg.branches)).filter(function (k) { return cfg.branches[k]; });
};
